"""Train and evaluate the knowledge-tracing model.

Real run (public data, produces the numbers that go in the README):
    python train.py --data data/skill_builder_data.csv \
        --export-ts ../../backend/src/mastery/mastery-model.ts

Pipeline smoke test (simulated students; results are labeled synthetic and the
model is never exported):
    python train.py --synthetic

Models compared on a STUDENT-level train/test split (no student appears in both):
    1. majority class                (floor)
    2. overall accuracy heuristic    (student's running accuracy, no skill info)
    3. skill accuracy heuristic      (running accuracy on the skill being asked)
    4. logistic regression           (all skill-agnostic features)
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import sklearn  # noqa: E402
from features import FEATURES, PRIOR, PRIOR_WEIGHT, RECENT_WINDOW, build_features  # noqa: E402
from sklearn.linear_model import LogisticRegression  # noqa: E402
from sklearn.metrics import (  # noqa: E402
    accuracy_score,
    brier_score_loss,
    log_loss,
    roc_auc_score,
    roc_curve,
)
from sklearn.model_selection import GroupShuffleSplit  # noqa: E402
from sklearn.preprocessing import StandardScaler  # noqa: E402
from synthetic import simulate  # noqa: E402


def load_assistments(path: Path) -> pd.DataFrame:
    """ASSISTments 2009-2010 "skill builder" export.

    Standard preparation: keep rows that have a skill, keep one row per
    interaction (the export repeats a row per skill of a multi-skill problem).
    """
    df = pd.read_csv(
        path,
        encoding="latin-1",
        usecols=["order_id", "user_id", "skill_id", "correct"],
        low_memory=False,
    )
    df = df.dropna(subset=["skill_id"]).drop_duplicates(subset="order_id")
    df = df[df["correct"].isin([0, 1])]
    df["skill_id"] = df["skill_id"].astype(int)
    return df.reset_index(drop=True)


def metrics(y: np.ndarray, p: np.ndarray, rng: np.random.Generator) -> dict:
    p = np.clip(p, 1e-6, 1 - 1e-6)
    boots = []
    n = len(y)
    for _ in range(200):
        idx = rng.integers(0, n, n)
        if y[idx].min() == y[idx].max():
            continue
        boots.append(roc_auc_score(y[idx], p[idx]))
    lo, hi = np.percentile(boots, [2.5, 97.5]) if boots else (float("nan"),) * 2
    return {
        "auc": float(roc_auc_score(y, p)),
        "auc_ci95": [float(lo), float(hi)],
        "accuracy": float(accuracy_score(y, p >= 0.5)),
        "log_loss": float(log_loss(y, p)),
        "brier": float(brier_score_loss(y, p)),
    }


def calibration_table(y: np.ndarray, p: np.ndarray, bins: int = 10) -> list[dict]:
    edges = np.quantile(p, np.linspace(0, 1, bins + 1))
    edges[0], edges[-1] = -np.inf, np.inf
    rows = []
    for lo, hi in zip(edges[:-1], edges[1:], strict=True):
        mask = (p > lo) & (p <= hi)
        if mask.sum():
            rows.append(
                {
                    "mean_predicted": float(p[mask].mean()),
                    "observed_rate": float(y[mask].mean()),
                    "n": int(mask.sum()),
                }
            )
    return rows


def export_ts(path: Path, model: dict) -> None:
    body = json.dumps(model, indent=2)
    path.write_text(
        "// GENERATED by ml/knowledge-tracing/train.py. Do not edit by hand.\n"
        "import type { MasteryModel } from './mastery.model';\n\n"
        f"export const MASTERY_MODEL: MasteryModel | null = {body};\n",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--data", type=Path, help="path to skill_builder_data.csv")
    ap.add_argument("--synthetic", action="store_true", help="use simulated students (smoke test)")
    ap.add_argument("--out", type=Path, default=Path("results"))
    ap.add_argument("--export-ts", type=Path, help="write the model for the NestJS API")
    ap.add_argument("--test-size", type=float, default=0.2)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    if args.synthetic == bool(args.data):
        ap.error("pass exactly one of --data or --synthetic")
    if args.synthetic and args.export_ts:
        ap.error("a model trained on synthetic data must never be exported")

    rng = np.random.default_rng(args.seed)
    source = "synthetic" if args.synthetic else "assistments-2009-2010-skill-builder"
    raw = simulate(seed=args.seed) if args.synthetic else load_assistments(args.data)
    data = build_features(raw)

    splitter = GroupShuffleSplit(n_splits=1, test_size=args.test_size, random_state=args.seed)
    train_idx, test_idx = next(splitter.split(data, groups=data["user_id"]))
    train, test = data.iloc[train_idx], data.iloc[test_idx]
    y_train, y_test = train["correct"].to_numpy(), test["correct"].to_numpy()
    assert set(train["user_id"]).isdisjoint(test["user_id"]), "student leaked across split"

    scaler = StandardScaler().fit(train[FEATURES])
    clf = LogisticRegression(max_iter=1000).fit(scaler.transform(train[FEATURES]), y_train)
    p_model = clf.predict_proba(scaler.transform(test[FEATURES]))[:, 1]

    # Majority class: always predict the more common training label. Constant
    # scores carry no ranking information, so AUC is 0.5 by definition.
    train_rate = float(np.clip(y_train.mean(), 1e-6, 1 - 1e-6))
    majority = float(train_rate >= 0.5)
    const_p = np.full(len(y_test), train_rate)
    results = {
        "majority_class": {
            "auc": 0.5,
            "auc_ci95": [0.5, 0.5],
            "accuracy": float((y_test == majority).mean()),
            "log_loss": float(log_loss(y_test, const_p)),
            "brier": float(brier_score_loss(y_test, const_p)),
        },
        "overall_accuracy_heuristic": metrics(y_test, test["overall_rate"].to_numpy(), rng),
        "skill_accuracy_heuristic": metrics(y_test, test["skill_rate"].to_numpy(), rng),
        "logistic_regression": metrics(y_test, p_model, rng),
    }

    args.out.mkdir(parents=True, exist_ok=True)
    report = {
        "data_source": source,
        "is_synthetic": bool(args.synthetic),
        "rows": int(len(data)),
        "students": int(data["user_id"].nunique()),
        "skills": int(data["skill_id"].nunique()),
        "train_students": int(train["user_id"].nunique()),
        "test_students": int(test["user_id"].nunique()),
        "test_rows": int(len(test)),
        "base_rate_correct": float(data["correct"].mean()),
        "split": {"kind": "student-level", "test_size": args.test_size, "seed": args.seed},
        "models": results,
        "calibration_logistic_regression": calibration_table(y_test, p_model),
        "coefficients": dict(zip(FEATURES, map(float, clf.coef_[0]), strict=True)),
        "environment": {
            "python": platform.python_version(),
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "scikit-learn": sklearn.__version__,
        },
    }
    (args.out / "results.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    fpr, tpr, _ = roc_curve(y_test, p_model)
    plt.figure(figsize=(4.5, 4.5))
    auc = results["logistic_regression"]["auc"]
    plt.plot(fpr, tpr, label=f"logistic regression (AUC {auc:.3f})")
    plt.plot([0, 1], [0, 1], "--", color="grey", label="chance")
    plt.xlabel("False positive rate")
    plt.ylabel("True positive rate")
    plt.title(f"ROC on held-out students ({source})", fontsize=8)
    plt.legend(loc="lower right", fontsize=8)
    plt.tight_layout()
    plt.savefig(args.out / "roc.png", dpi=150)
    plt.close()

    cal = report["calibration_logistic_regression"]
    plt.figure(figsize=(4.5, 4.5))
    plt.plot([c["mean_predicted"] for c in cal], [c["observed_rate"] for c in cal], "o-")
    plt.plot([0, 1], [0, 1], "--", color="grey")
    plt.xlabel("Mean predicted probability")
    plt.ylabel("Observed rate correct")
    plt.title("Calibration (deciles of predictions)", fontsize=8)
    plt.tight_layout()
    plt.savefig(args.out / "calibration.png", dpi=150)
    plt.close()

    if args.export_ts:
        export_ts(
            args.export_ts,
            {
                "version": 1,
                "features": FEATURES,
                "mean": [float(x) for x in scaler.mean_],
                "scale": [float(x) for x in scaler.scale_],
                "coef": [float(x) for x in clf.coef_[0]],
                "intercept": float(clf.intercept_[0]),
                "prior": PRIOR,
                "priorWeight": PRIOR_WEIGHT,
                "recentWindow": RECENT_WINDOW,
                "trainedOn": {
                    "dataset": source,
                    "rows": report["rows"],
                    "students": report["students"],
                },
                "heldOut": {
                    "auc": results["logistic_regression"]["auc"],
                    "accuracy": results["logistic_regression"]["accuracy"],
                },
            },
        )

    print(f"data: {source}  rows={report['rows']}  students={report['students']}")
    for name, m in results.items():
        print(
            f"{name:30s} AUC {m['auc']:.3f}  acc {m['accuracy']:.3f}  logloss {m['log_loss']:.3f}"
        )
    print(f"wrote {args.out}/results.json, roc.png, calibration.png")
    return 0


if __name__ == "__main__":
    sys.exit(main())
